-- Knowledge enrichment (#24): facts proposed by members, with their review history.
-- GLOBAL proposals need a cited source and a curator's approval; SPACE ones apply at once, to their space only.
create table knowledge_proposal (
    id             bigint generated by default as identity primary key,
    space_id       bigint       not null references space (id),
    scope          varchar(10)  not null check (scope in ('GLOBAL', 'SPACE')),
    kind           varchar(10)  not null check (kind in ('ALIAS', 'PAIR', 'HOST')),
    -- ALIAS: another name for a crop or an organism
    target_id      varchar(50),
    alias_name     varchar(100),
    alias_language varchar(5),
    -- PAIR: crop_id is a companion or antagonist of partner_id; HOST: organism_id affects crop_id
    crop_id        varchar(50),
    partner_id     varchar(50),
    relation       varchar(12) check (relation in ('COMPANION', 'ANTAGONIST')),
    effect         varchar(300),
    organism_id    varchar(10),
    from_month     integer check (from_month between 1 and 12),
    to_month       integer check (to_month between 1 and 12),
    citation       varchar(500),
    proposed_by    varchar(100) not null,
    created_at     timestamp with time zone not null,
    status         varchar(10)  not null check (status in ('PENDING', 'APPROVED', 'REJECTED')),
    reviewed_by    varchar(100),
    reviewed_at    timestamp with time zone,
    review_note    varchar(500)
);

create index knowledge_proposal_status on knowledge_proposal (status, scope);
create index knowledge_proposal_space on knowledge_proposal (space_id);
