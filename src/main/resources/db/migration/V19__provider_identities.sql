-- Provider-independent identities (#28): a person is no longer a GitHub login but a user name of our own,
-- linked to one or more external identities.
alter table app_user rename column github_login to login;

-- A provider's stable identifier for a person (GitHub's numeric id, Google's subject), with the address
-- the provider verified. Existing GitHub identities are recorded at the next sign-in, since the ids we
-- never stored cannot be recovered from the login.
create table user_identity (
    id        bigint generated by default as identity primary key,
    user_id   bigint       not null references app_user (id) on delete cascade,
    provider  varchar(20)  not null check (provider in ('github', 'google')),
    subject   varchar(200) not null,
    email     varchar(320),
    linked_at timestamp with time zone not null,
    unique (provider, subject),
    unique (user_id, provider)
);
