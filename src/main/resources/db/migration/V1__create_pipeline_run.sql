-- One finished pipeline run (HUMAN review mode, started from the UI).
create table pipeline_run (
    id                  bigint generated by default as identity primary key,
    process_id          varchar(100)     not null,
    question_id         varchar(50)      not null,
    question            text             not null,
    noise_dropout       double precision not null,
    noise_spurious      integer          not null,
    noise_mislabel      double precision not null,
    noise_near_subject  boolean          not null,
    noise_seed          bigint           not null,
    decision_answer     text[]           not null,
    decision_confidence double precision not null,
    decision_escalated  boolean          not null,
    decision_reason     text             not null,
    answer              text[]           not null,
    answered_by_human   boolean          not null,
    reviewer            varchar(100),
    answer_text         text             not null,
    -- null when the question is not one of the experiment cases
    jena_answer         text[],
    matches_jena        boolean,
    finished_at         timestamp with time zone not null
);

create index pipeline_run_finished_at on pipeline_run (finished_at desc);
