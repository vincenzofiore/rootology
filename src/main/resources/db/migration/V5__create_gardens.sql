-- My garden (#14): sites with plots and what grows in them, owned by a shared space.
create table garden (
    id         bigint generated by default as identity primary key,
    space_id   bigint       not null references space (id),
    name       varchar(200) not null,
    -- coarse location only: a town, and coordinates rounded to 0.01 degrees (about 1 km)
    town       varchar(200),
    latitude   numeric(5, 2) check (latitude between -90 and 90),
    longitude  numeric(5, 2) check (longitude between -180 and 180),
    created_at timestamp with time zone not null
);

create table plot (
    id        bigint generated by default as identity primary key,
    garden_id bigint       not null references garden (id) on delete cascade,
    name      varchar(100) not null,
    kind      varchar(20)  not null check (kind in ('GROUND', 'RAISED_BED', 'CONTAINER')),
    soil      varchar(20)  not null check (soil in ('SANDY', 'LOAMY', 'CLAY', 'SILTY', 'POTTING_MIX', 'UNKNOWN')),
    area_m2   numeric(8, 2) check (area_m2 > 0),
    unique (garden_id, name)
);

create table planting (
    id         bigint generated by default as identity primary key,
    plot_id    bigint       not null references plot (id) on delete cascade,
    crop_id    varchar(50)  not null,
    method     varchar(20)  not null check (method in ('SOWN', 'TRANSPLANTED')),
    planted_on date         not null,
    ended_on   date,
    notes      varchar(500),
    check (ended_on is null or ended_on >= planted_on)
);

create index garden_space on garden (space_id);
