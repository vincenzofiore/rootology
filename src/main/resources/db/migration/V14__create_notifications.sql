-- Notifications (#26): one row per recipient, which is also the outbox of the email digest.
create table notification (
    id           bigint generated by default as identity primary key,
    recipient    varchar(100) not null,
    space_id     bigint       not null,
    kind         varchar(30)  not null check (kind in ('ESCALATION_WAITING')),
    process_id   varchar(100),
    title        varchar(200) not null,
    body         varchar(1000) not null,
    created_at   timestamp with time zone not null,
    read_at      timestamp with time zone,
    emailed_at   timestamp with time zone,
    resolved_at  timestamp with time zone,
    resolved_by  varchar(100)
);

create index notification_recipient on notification (recipient, created_at);
create index notification_process on notification (process_id);

-- Per person: where and whether to email, and quiet hours (Italian time; from > to wraps past midnight).
create table notification_preference (
    github_login      varchar(100) primary key,
    email             varchar(254),
    email_escalations boolean not null default true,
    quiet_from        time,
    quiet_to          time
);
