-- An account the nightly signal found creating only useless traffic (#165): it signed in days ago, is a member
-- of no space with a garden, and its recent questions are mostly off-domain. The counts that made it are kept
-- so an admin decides on facts, not on the system's word; the decision is a person's, always (GDPR art. 22).
-- An account is flagged once: one open flag per login, and no new flag after a decided one.
create table account_flag (
    id                   bigint generated by default as identity primary key,
    login                varchar(100)             not null,
    flagged_at           timestamp with time zone not null,
    judged_questions     integer                  not null,
    off_domain_questions integer                  not null,
    days_without_garden  integer                  not null,
    status               varchar(16)              not null,
    decided_by           varchar(100),
    decided_at           timestamp with time zone,
    constraint account_flag_status_check check (status in ('OPEN', 'BLOCKED', 'DISMISSED'))
);

-- At most one flag waits for an admin: the nightly signal adds nothing while one is open.
create unique index account_flag_one_open on account_flag (login) where status = 'OPEN';

-- The admins are told of a flag (#165) through the same outbox as an invitation request: a kind of its own,
-- with no space, since it is about the app and not about a garden.
alter table notification drop constraint notification_kind_check;
alter table notification add constraint notification_kind_check
    check (kind in ('ESCALATION_WAITING', 'ESCALATION_ANSWERED', 'WEATHER_ALERT', 'ACCESS_REQUEST', 'MEMBERSHIP', 'ACCOUNT_FLAG'));
