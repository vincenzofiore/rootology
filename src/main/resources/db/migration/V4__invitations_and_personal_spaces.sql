-- Invitations to a shared space (#23). Only a hash of the token is stored; the link holds the token.
create table invitation (
    id            bigint generated by default as identity primary key,
    space_id      bigint       not null references space (id),
    token_hash    varchar(64)  not null unique,
    role          varchar(20)  not null check (role in ('OWNER', 'MEMBER')),
    -- when set, only this GitHub login (lower case) may accept it
    invited_login varchar(100),
    created_by    varchar(100) not null,
    created_at    timestamp with time zone not null,
    expires_at    timestamp with time zone not null,
    accepted_by   varchar(100),
    accepted_at   timestamp with time zone,
    revoked_at    timestamp with time zone
);

-- The personal space of a person cannot be left; mark which space is whose.
alter table space add column personal_of bigint references app_user (id);
update space s set personal_of = m.user_id
from space_member m, app_user u
where m.space_id = s.id and m.user_id = u.id and m.role = 'OWNER' and s.name = u.github_login || '''s garden';
