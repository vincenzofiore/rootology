-- Shared spaces (#15): a person, a space (a garden or a farm), and who belongs to which.
create table app_user (
    id           bigint generated by default as identity primary key,
    github_login varchar(100) not null unique,
    created_at   timestamp with time zone not null
);

create table space (
    id         bigint generated by default as identity primary key,
    name       varchar(200) not null,
    created_at timestamp with time zone not null
);

create table space_member (
    id        bigint generated by default as identity primary key,
    space_id  bigint      not null references space (id),
    user_id   bigint      not null references app_user (id),
    role      varchar(20) not null check (role in ('OWNER', 'MEMBER')),
    joined_at timestamp with time zone not null,
    unique (space_id, user_id)
);

-- Runs now belong to a space and record who started them. Runs stored before #15 have no
-- space and are no longer shown.
alter table pipeline_run add column space_id bigint references space (id);
alter table pipeline_run add column started_by varchar(100);
create index pipeline_run_space_finished_at on pipeline_run (space_id, finished_at desc);
