-- Usage of the paid services per person (#19): one row per pipeline run started by someone, and
-- personal daily limits set by an admin (otherwise the configured default applies).
create table usage_record (
    id                bigint generated by default as identity primary key,
    github_login      varchar(100) not null,
    space_id          bigint       not null,
    kind              varchar(10)  not null check (kind in ('QUESTION', 'REVIEW')),
    at                timestamp with time zone not null,
    claude_calls      integer      not null,
    prompt_tokens     integer      not null,
    completion_tokens integer      not null,
    cost_usd          double precision not null,
    jev_calls         integer      not null
);

create index usage_record_login_at on usage_record (github_login, at);

create table usage_limit (
    github_login    varchar(100) primary key,
    daily_questions integer      not null check (daily_questions >= 0),
    set_by          varchar(100) not null,
    set_at          timestamp with time zone not null
);
