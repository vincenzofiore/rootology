-- Invitation requests (#65). A person who signed in with GitHub or Google but is not admitted asks for
-- access; an admin approves or rejects it. Nothing about a person is written before they are admitted, so a
-- request is keyed by the identity the provider gave (provider and stable id) and keeps the login the app
-- would give them, the address the provider verified, the motivation, and who decided.
create table access_request (
    id           bigint generated by default as identity primary key,
    provider     varchar(20)  not null check (provider in ('GITHUB', 'GOOGLE')),
    subject      varchar(100) not null,
    login        varchar(100) not null,
    email        varchar(254),
    motivation   varchar(500) not null,
    status       varchar(20)  not null check (status in ('PENDING', 'APPROVED', 'REJECTED')),
    created_at   timestamp with time zone not null,
    decided_by   varchar(100),
    decided_at   timestamp with time zone
);

-- One open request per identity: a person asks again only after a rejection's waiting time.
create unique index access_request_one_pending on access_request (provider, subject) where status = 'PENDING';

-- The daily cap, and the nightly retention of decided and forgotten requests.
create index access_request_created on access_request (created_at);
create index access_request_decided on access_request (status, decided_at);

-- Admins are notified of a new request through the same outbox as questions and weather alerts (#26, #38).
-- That notification belongs to no space: it is about the app.
alter table notification alter column space_id drop not null;
alter table notification drop constraint notification_kind_check;
alter table notification add constraint notification_kind_check
    check (kind in ('ESCALATION_WAITING', 'ESCALATION_ANSWERED', 'WEATHER_ALERT', 'ACCESS_REQUEST'));
alter table notification add constraint notification_access_request_space
    check (kind <> 'ACCESS_REQUEST' or space_id is null);
