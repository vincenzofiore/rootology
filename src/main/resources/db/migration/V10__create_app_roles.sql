-- App-wide roles (#32): who holds which role, granted and revoked by whom and when. A revoked grant stays
-- as history; at most one active grant per person and role.
create table app_role_grant (
    id           bigint generated by default as identity primary key,
    github_login varchar(100) not null,
    role         varchar(10)  not null check (role in ('ADMIN', 'CURATOR', 'QA')),
    granted_by   varchar(100) not null,
    granted_at   timestamp with time zone not null,
    revoked_by   varchar(100),
    revoked_at   timestamp with time zone
);

create unique index app_role_grant_active on app_role_grant (github_login, role) where revoked_at is null;
